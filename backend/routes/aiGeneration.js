// Helper function to get or create generation session
const getOrCreateGenerationSession = async (documentId, userId) => {
  const document = await DocumentUpload.findById(documentId);

  if (!document) {
    throw new Error('Document not found');
  }

  // Check if session exists in memory
  if (document.generationSessionId && generationSessions[document.generationSessionId]) {
    const session = generationSessions[document.generationSessionId];
    if (session.userId.toString() !== userId.toString()) {
      throw new Error('This document is being generated by another user');
    }
    return session;
  }

  // Create new session
  const sessionId = Date.now().toString();

  // Convert stored unitContents from object to array
  let unitContentsArray = [];
  if (document.generationProgress?.unitContents) {
    if (typeof document.generationProgress.unitContents === 'object' && !Array.isArray(document.generationProgress.unitContents)) {
      unitContentsArray = Object.values(document.generationProgress.unitContents);
    } else if (Array.isArray(document.generationProgress.unitContents)) {
      unitContentsArray = document.generationProgress.unitContents;
    }
  }

  const newSession = {
    sessionId,
    documentId: document._id,
    documentPath: document.filePath,
    documentName: document.originalName,
    userId,
    step: document.generationStatus || 'overview',
    data: {
      overview: document.generationProgress?.overview || null,
      units: document.generationProgress?.units || [],
      unitContents: unitContentsArray,
      completedUnits: document.generationProgress?.completedUnits || []
    },
    createdAt: new Date()
  };

  generationSessions[sessionId] = newSession;

  // Update document with session info
  document.generationSessionId = sessionId;
  if (document.generationStatus === 'not_started') {
    document.generationStatus = 'overview_generated';
  }
  await document.save();

  return newSession;
};

// Helper functions
const calculateTotalDuration = (unitContents) => {
  if (!unitContents || !Array.isArray(unitContents)) return 0;
  return unitContents.reduce((total, unit) => {
    return total + calculateUnitDuration(unit);
  }, 0);
};

const calculateTotalXP = (unitContents) => {
  if (!unitContents || !Array.isArray(unitContents)) return 0;
  return unitContents.reduce((total, unit) => {
    return total + calculateUnitXP(unit);
  }, 0);
};

const calculateUnitDuration = (unitContent) => {
  if (!unitContent || !unitContent.screens) return 30;
  return unitContent.screens.length * 2;
};

const calculateUnitXP = (unitContent) => {
  if (!unitContent || !unitContent.screens) return 25;

  let totalXP = 0;
  unitContent.screens.forEach(screen => {
    if (screen.type === 'concept-check' && screen.questions) {
      screen.questions.forEach(q => {
        totalXP += q.xp || 5;
      });
    } else if (screen.type === 'coding') {
      totalXP += screen.xp || 10;
    }
  });
  return totalXP || 25;
};

const extractKeyTakeaways = (unitContent) => {
  if (!unitContent || !unitContent.screens) {
    return [`Master ${unitContent?.title || 'this unit'}`];
  }

  const takeawaysScreen = unitContent.screens.find(
    screen => screen.title?.toLowerCase().includes('takeaway')
  );

  if (takeawaysScreen?.description) {
    const lines = takeawaysScreen.description.split('\n');
    const takeaways = lines
      .filter(line => line.trim().startsWith('•') || line.trim().startsWith('-') || line.trim().match(/^\d+\./))
      .map(line => line.replace(/^[•\- \d\.]+/, '').trim())
      .filter(t => t.length > 0);

    if (takeaways.length > 0) return takeaways;
  }

  return [
    `Understand core concepts of ${unitContent?.title || 'this unit'}`,
    'Apply the knowledge in practical scenarios',
    'Complete the exercises to reinforce learning'
  ];
};

