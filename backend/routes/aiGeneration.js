// AI Field Improvement - Generate Suggestion
router.post('/suggest-improvement/:courseId', protect, admin, async (req, res) => {
  try {
    const { fieldType, currentValue, feedback, context } = req.body;

    let prompt = '';
    switch (fieldType) {
      case 'course_title':
        prompt = `Improve this course title: "${currentValue}"
Feedback: ${feedback}
Requirements: Make it engaging, clear, and descriptive. Keep under 60 characters.
Return ONLY the improved title as a JSON string: {"title": "Improved Title"}`;
        break;
      case 'learning_objectives':
        prompt = `Improve these learning objectives based on feedback:
Current: ${Array.isArray(currentValue) ? currentValue.join('\n') : currentValue}
Feedback: ${feedback}
Requirements: Make them specific, measurable, action-oriented. Use Bloom's taxonomy verbs.
Return ONLY a JSON array: ["Objective 1", "Objective 2"]`;
        break;
      case 'unit_title':
        prompt = `Improve this unit title: "${currentValue}"
Course: ${context?.courseTitle || ''}
Feedback: ${feedback}
Requirements: Clear, engaging, under 50 characters.
Return ONLY: {"title": "Improved Title"}`;
        break;
      case 'unit_message':
        prompt = `Improve this welcome message: "${currentValue}"
Unit: ${currentValue}
Feedback: ${feedback}
Requirements: Motivating, clear, under 100 characters.
Return ONLY: {"message": "Improved welcome message"}`;
        break;
      case 'key_takeaways':
        prompt = `Improve these key takeaways:
Current: ${Array.isArray(currentValue) ? currentValue.join('\n') : currentValue}
Feedback: ${feedback}
Requirements: Make them actionable, memorable, 3-5 bullet points.
Return ONLY a JSON array: ["Takeaway 1", "Takeaway 2"]`;
        break;
      case 'screen_description':
        prompt = `Improve this screen content:
${currentValue}
Feedback: ${feedback}
Requirements: Keep the same length, make it clearer, add examples if helpful.
Return ONLY: {"description": "Improved description"}`;
        break;
      default:
        return res.status(400).json({ message: 'Unknown field type' });
    }

    // Call Python AI service
    const pythonResponse = await axios.post(
      'http://localhost:8000/generate-prompt',
      { prompt, response_format: 'json' },
      { timeout: 30000 }
    );

    let suggestion = pythonResponse.data.response;
    try {
      const parsed = JSON.parse(suggestion);
      suggestion = parsed.title || parsed.message || parsed.description || (Array.isArray(parsed) ? parsed : suggestion);
    } catch (e) {
      // Keep as is if not JSON
    }

    res.json({ suggestion });
  } catch (error) {
    console.error('Suggestion error:', error);
    res.status(500).json({ message: error.message });
  }
});

